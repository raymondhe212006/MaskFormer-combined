"""Tests of the numpy port of hepattn's VarTransform used by the plotting chain
(src/scripts/plot/hgcal_eval_common.py): the transformed node-feature plots must apply exactly
what the dataset applies.  Torch-free; the cross-check against hepattn runs only when it is
importable.

    PYTHONPATH=src python -m pytest tests/test_scale_transform.py -q
"""

import sys
from pathlib import Path

import numpy as np
import pytest

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src" / "scripts" / "plot"))
sys.path.insert(0, str(REPO / "src"))

from hgcal_eval_common import (  # noqa: E402
    NODE_SCALE_KEY, FeatureScalerNP, VarTransformNP, load_scale_dict,
)

CONFIGS = {
    "e": dict(type="std", fn="log", mean=1.0, std=2.0),
    "e1p": dict(type="std", fn="log1p", mean=0.5, std=0.8),
    "x": dict(type="min_max", min=0.0, max=4.0),
    "r": dict(type="min_max_sym", min=1.0, max=3.0, fn="sqrt"),
    "eta": dict(type="min_max_sym", min=1.4, max=3.1),
    "sinphi": dict(type="std", mean=0.0, std=1.0),
}


def test_std_log():
    tr = VarTransformNP("e", CONFIGS["e"])
    x = np.array([1.0, np.e, np.e ** 2])
    np.testing.assert_allclose(tr.transform(x), [-0.5, 0.0, 0.5])
    np.testing.assert_allclose(tr.inverse_transform(tr.transform(x)), x)
    assert tr.describe() == "(log(x) - 1) / 2"


def test_min_max():
    tr = VarTransformNP("x", CONFIGS["x"])
    np.testing.assert_allclose(tr.transform([0.0, 2.0, 4.0]), [0.0, 0.5, 1.0])
    np.testing.assert_allclose(tr.inverse_transform([0.0, 0.5, 1.0]), [0.0, 2.0, 4.0])


def test_min_max_sym_sqrt():
    tr = VarTransformNP("r", CONFIGS["r"])
    assert tr.shift == 2.0 and tr.scale == 1.0
    np.testing.assert_allclose(tr.transform([1.0, 4.0, 9.0]), [-1.0, 0.0, 1.0])
    np.testing.assert_allclose(tr.inverse_transform([-1.0, 0.0, 1.0]), [1.0, 4.0, 9.0])


def test_log1p_and_domain():
    tr = VarTransformNP("e", CONFIGS["e1p"])
    np.testing.assert_allclose(tr.transform([0.0]), [(0.0 - 0.5) / 0.8])
    np.testing.assert_allclose(tr.inverse_transform(tr.transform([0.0, 3.0, 50.0])), [0.0, 3.0, 50.0])
    # log of 0 / a negative value gives a non-finite number, never an exception
    y = VarTransformNP("e", CONFIGS["e"]).transform([0.0, -1.0, 2.0])
    assert not np.isfinite(y[0]) and not np.isfinite(y[1]) and np.isfinite(y[2])


def test_defaults_and_errors(capsys):
    tr = VarTransformNP("anything", {})
    assert tr.is_identity and tr.type == "std"
    np.testing.assert_allclose(tr.transform([1.0, 2.0]), [1.0, 2.0])
    assert VarTransformNP("sinphi", CONFIGS["sinphi"]).is_identity
    with pytest.raises(ValueError):
        VarTransformNP("bad", dict(type="robust"))
    tr = VarTransformNP("odd", dict(type="std", fn="cbrt", mean=0.0, std=2.0))
    assert "ignored" in capsys.readouterr().out
    np.testing.assert_allclose(tr.transform([4.0]), [2.0])    # the unknown fn is skipped
    assert tr.describe() == "(x - 0) / 2"


def test_load_scale_dict_and_missing_key(tmp_path, capsys):
    path = tmp_path / "node_var_transform.yaml"
    path.write_text(
        "# Generated by compute_norm_par.py\n"
        "# NOTE: comments and blank lines are fine\n\n"
        "e:\n  type: std\n  fn: log\n  mean: 1.55\n  std: 1.175\n  min: -0.426\n  max: 4.898\n"
        "eta:\n  type: min_max_sym\n  mean: 2.232\n  std: 0.416\n  min: 1.359\n  max: 3.121\n"
        "sinphi:\n  type: std\n  mean: 0.0\n  std: 1.0\n")
    d = load_scale_dict(str(path))
    assert set(d) == {"e", "eta", "sinphi"}
    assert d["e"].fn == "log" and d["e"].shift == 1.55 and d["e"].scale == 1.175
    assert d["eta"].type == "min_max_sym"
    np.testing.assert_allclose(d["eta"].transform([1.359, 3.121]), [-1.0, 1.0])

    scaler = FeatureScalerNP(str(path))
    assert "e" in scaler and "t" not in scaler
    assert scaler["e"] is d["e"] or scaler["e"].describe() == d["e"].describe()
    assert scaler["t"].is_identity                        # missing key -> identity, warned once
    scaler["t"]
    out = capsys.readouterr().out
    assert out.count("not in the scale dict") == 1
    # the dataset's feature -> key map
    assert NODE_SCALE_KEY == {"e": "e", "eta": "eta", "r": "r", "time": "t"}
    # a dict of configs works too
    s2 = FeatureScalerNP({"e": CONFIGS["e"]})
    np.testing.assert_allclose(s2["e"].transform([np.e]), [0.0])


def test_real_scale_dicts_load():
    for name in ("hgcal_trackster_clue3dhigh_var_transform.yaml", "hgcal_simtrackster_var_transform.yaml"):
        path = REPO / "configs" / name
        if not path.is_file():
            pytest.skip("%s not in the checkout" % name)
        d = load_scale_dict(str(path))
        assert {"e", "eta", "r", "sinphi", "cosphi"} <= set(d)
        assert all(np.isfinite([t.shift, t.scale]).all() and t.scale > 0 for t in d.values())


def test_matches_hepattn():
    scaling = pytest.importorskip("hepattn.utils.scaling")
    torch = pytest.importorskip("torch")
    rng = np.random.default_rng(5)
    for name, cfg in CONFIGS.items():
        ours = VarTransformNP(name, cfg)
        theirs = scaling.VarTransform(name, cfg)
        x = rng.uniform(1.0, 9.0, 1000)
        np.testing.assert_allclose(ours.transform(x), theirs.transform(torch.tensor(x)).numpy(), rtol=1e-6)
        y = rng.uniform(-1.0, 1.0, 1000)
        np.testing.assert_allclose(ours.inverse_transform(y),
                                   theirs.inverse_transform(torch.tensor(y)).numpy(), rtol=1e-6)
